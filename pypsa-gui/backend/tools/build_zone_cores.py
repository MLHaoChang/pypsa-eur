"""
Regenerate `services/market_zone_cores.py`, the bundled site-pin → bidding-zone
lookup of SCU06 S1 (`services/market_prices.zone_for_pin`).

A dev tool, never imported by the app: the app ships only the generated
rectangles and has no GIS dependency at run time. Run it from the backend
directory with the GUI venv (geopandas, shapely):

    python tools/build_zone_cores.py <naturalearth_lowres.shp>

The input is Natural Earth 1:110m admin-0 (public domain), for example the copy
pyogrio ships as a test fixture. For each single-zone country it keeps the
0.25° cells lying wholly inside the border pulled 0.2° inward, merged into
rectangles. A pin outside every core (near a border, a coast, or in a
multi-zone country) resolves to no zone, so the lookup never guesses.
"""

from __future__ import annotations

import sys
from pathlib import Path

import geopandas as gpd
import numpy as np
from shapely.geometry import box

CELL = 0.25
INWARD = 0.2
# Zone → Natural Earth country names. Multi-zone countries (DK, IT, NO, SE)
# are deliberately absent: a country border cannot place a pin in DK1 or NO2.
ZONES: dict[str, tuple[str, ...]] = {
    "DE-LU": ("Germany", "Luxembourg"),
    "NL": ("Netherlands",),
    "BE": ("Belgium",),
    "FR": ("France",),
    "AT": ("Austria",),
    "PL": ("Poland",),
    "CZ": ("Czechia",),
    "SK": ("Slovakia",),
    "HU": ("Hungary",),
    "SI": ("Slovenia",),
    "HR": ("Croatia",),
    "RO": ("Romania",),
    "BG": ("Bulgaria",),
    "GR": ("Greece",),
    "ES": ("Spain",),
    "PT": ("Portugal",),
    "FI": ("Finland",),
    "EE": ("Estonia",),
    "LV": ("Latvia",),
    "LT": ("Lithuania",),
    "CH": ("Switzerland",),
    "RS": ("Serbia",),
    "IE-SEM": ("Ireland",),
}
# Mainland only: overseas France and the Canaries are not in these zones, and
# Corsica is outside the French day-ahead zone.
CLIP = {"FR": box(-5.5, 42.0, 8.3, 51.5), "ES": box(-10.0, 35.5, 4.0, 44.5)}


def cores(
    shapes: gpd.GeoDataFrame,
) -> dict[str, list[tuple[float, float, float, float]]]:
    out: dict[str, list[tuple[float, float, float, float]]] = {}
    for zone, names in ZONES.items():
        geom = shapes[shapes["name"].isin(names)].union_all()
        if zone in CLIP:
            geom = geom.intersection(CLIP[zone])
        inner = geom.buffer(-INWARD)
        x0, y0, x1, y1 = geom.bounds
        rows: list[tuple[float, float, float, float]] = []
        for y in np.arange(np.floor(y0 / CELL) * CELL, y1, CELL):
            run: list[float] | None = None
            for x in np.arange(np.floor(x0 / CELL) * CELL, x1 + CELL, CELL):
                if inner.contains(box(x, y, x + CELL, y + CELL)):
                    run = [run[0], x + CELL] if run else [x, x + CELL]
                elif run:
                    rows.append(
                        (
                            round(run[0], 2),
                            round(y, 2),
                            round(run[1], 2),
                            round(y + CELL, 2),
                        )
                    )
                    run = None
            if run:
                rows.append(
                    (
                        round(run[0], 2),
                        round(y, 2),
                        round(run[1], 2),
                        round(y + CELL, 2),
                    )
                )
        rows.sort(key=lambda r: (r[0], r[2], r[1]))
        merged: list[tuple[float, float, float, float]] = []
        for r in rows:  # stack runs with the same x-span into one rectangle
            if (
                merged
                and merged[-1][0] == r[0]
                and merged[-1][2] == r[2]
                and merged[-1][3] == r[1]
            ):
                merged[-1] = (r[0], merged[-1][1], r[2], r[3])
            else:
                merged.append(r)
        out[zone] = sorted(merged, key=lambda r: (r[1], r[0]))
    return out


def render(table: dict[str, list[tuple[float, float, float, float]]]) -> str:
    lines = [
        '"""',
        "GENERATED by tools/build_zone_cores.py from Natural Earth 1:110m admin-0",
        "(public domain). Do not edit by hand.",
        "",
        "Zone → rectangles (west, south, east, north in degrees) lying wholly inside",
        f"the zone's border pulled {INWARD}° inward ({CELL}° cells). A pin in none of them",
        "has no zone from the pin (`services/market_prices.zone_for_pin`).",
        '"""',
        "",
        "CORES: dict[str, tuple[tuple[float, float, float, float], ...]] = {",
    ]
    for zone, rects in table.items():
        lines.append(f'    "{zone}": (')
        lines += [f"        ({w}, {s}, {e}, {n})," for w, s, e, n in rects]
        lines.append("    ),")
    lines.append("}")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    target = (
        Path(__file__).resolve().parent.parent / "services" / "market_zone_cores.py"
    )
    target.write_text(render(cores(gpd.read_file(sys.argv[1]))), encoding="utf-8")
    print(f"wrote {target}")
