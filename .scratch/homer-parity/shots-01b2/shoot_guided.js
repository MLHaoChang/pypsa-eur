const { chromium } = require('playwright')
;(async () => {
  const browser = await chromium.launch()
  const ctx = await browser.newContext({ storageState: __dirname + '/state.json', viewport: { width: 1440, height: 900 }, deviceScaleFactor: 1 })
  await ctx.addInitScript(() => { localStorage.setItem('network-diagram:theme', 'light'); localStorage.setItem('network-diagram:theme-schema', '2') })
  const page = await ctx.newPage()
  await page.goto('http://127.0.0.1:5173/')
  await page.waitForTimeout(3000)
  await page.getByText('or-shots', { exact: true }).first().click({ force: true })
  await page.waitForTimeout(5000)
  await page.getByText('Guided', { exact: true }).first().click(); await page.waitForTimeout(2000)
  await page.evaluate(async () => {
    const m = await import('/src/layout/flowNavigation.ts')
    m.openFlowTargetInPlace({ section: 'scenarios', panel: 'simparams', component: null, entity: null, field: null })
  })
  await page.waitForTimeout(2500)
  await page.getByText('Network', { exact: true }).first().click()
  await page.waitForTimeout(1500)
  const block = page.getByTestId('offgrid-constraints')
  await block.scrollIntoViewIfNeeded()
  const f = l => block.getByLabel(l, { exact: true })
  console.log('block visible', await block.isVisible())
  await f('Reserve for load (%)').fill('10'); await f('Reserve for solar output (%)').fill('20'); await f('Reserve for wind output (%)').fill('15'); await page.evaluate(() => document.activeElement && document.activeElement.blur())
  await page.waitForTimeout(500)
  await page.screenshot({ path: __dirname + '/guided-light-set.png' })
  await browser.close()
})()
