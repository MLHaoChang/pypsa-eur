const { chromium } = require('playwright')
;(async () => {
  const browser = await chromium.launch()
  const ctx = await browser.newContext({ storageState: __dirname + '/state.json', viewport: { width: 1440, height: 900 }, deviceScaleFactor: 1 })
  const page = await ctx.newPage()
  await page.goto('http://127.0.0.1:5173/')
  await page.waitForTimeout(3000)
  await page.getByText('rf-shots', { exact: true }).first().click({ force: true })
  await page.waitForTimeout(5000)
  await page.getByText('Expert', { exact: true }).first().click(); await page.waitForTimeout(2500)
  await page.getByText('Log', { exact: true }).first().click({ force: true })
  await page.waitForTimeout(2000)
  await page.getByText('Run LOPF').first().click()
  await page.waitForTimeout(1500)
  const go = page.getByRole('button', { name: /^Run/ }).last()
  if (await go.isVisible().catch(() => false)) await go.click().catch(() => {})
  const line = page.getByText(/Minimum renewable fraction: the target/).first()
  await line.waitFor({ timeout: 150000 })
  await line.scrollIntoViewIfNeeded()
  await page.waitForTimeout(500)
  await page.screenshot({ path: __dirname + '/light-infeasible-log.png' })
  await browser.close()
})()
